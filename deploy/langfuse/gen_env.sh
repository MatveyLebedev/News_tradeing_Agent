#!/usr/bin/env bash
# Generate deploy/langfuse/.env with fresh random secrets for the Langfuse stack.
#
# Never prints a secret: only variable names. Run it where the stack runs (laptop or server),
# so secrets are born on that machine and never travel through a terminal or a transcript.
#
#   deploy/langfuse/gen_env.sh                         # local: UI on http://localhost:3000
#   LANGFUSE_PORT=3100 deploy/langfuse/gen_env.sh      # another port (NEXTAUTH_URL follows)
#
# Refuses to overwrite an existing .env: ENCRYPTION_KEY and SALT protect data already stored,
# so regenerating them on a live instance breaks it.

set -euo pipefail
cd "$(dirname "$0")"

if [[ -e .env ]]; then
    echo "✗ $(pwd)/.env exists — refusing to overwrite (it keys the data already stored)" >&2
    exit 1
fi

PORT="${LANGFUSE_PORT:-3000}"
EMAIL="${LANGFUSE_ADMIN_EMAIL:-admin@trade-agent.local}"
r() { openssl rand -hex "$1"; }

umask 077
cat > .env <<EOF
# Generated by gen_env.sh on $(date -u +%Y-%m-%dT%H:%MZ). Mode 600. Never commit, never copy off this host.
LANGFUSE_PORT=${PORT}
MINIO_PORT=${MINIO_PORT:-9090}
NEXTAUTH_URL=http://localhost:${PORT}
NEXTAUTH_SECRET=$(r 32)
SALT=$(r 32)
ENCRYPTION_KEY=$(r 32)
POSTGRES_PASSWORD=$(r 24)
CLICKHOUSE_PASSWORD=$(r 24)
REDIS_AUTH=$(r 24)
MINIO_ROOT_PASSWORD=$(r 24)
LANGFUSE_INIT_PROJECT_PUBLIC_KEY=pk-lf-$(r 16)
LANGFUSE_INIT_PROJECT_SECRET_KEY=sk-lf-$(r 24)
LANGFUSE_INIT_USER_EMAIL=${EMAIL}
LANGFUSE_INIT_USER_PASSWORD=$(r 12)
EOF

if [[ "${SMALL_HOST:-0}" == 1 ]]; then
    # The trading server (2 vCPU / 3.8 GiB, shared with Postgres + Neo4j): ~3.5 GiB of caps
    # over ~1.6 GiB idle. oom_score_adj in the compose file decides who dies if that is wrong.
    # Web heap 512 MB crash-looped on start (V8 "heap out of memory", 4 restarts in 10 min,
    # 2026-10-28); 1024 MB is the floor for Next.js here.
    cat >> .env <<'EOF'
WEB_MEM_LIMIT=1280m
WEB_NODE_HEAP_MB=1024
WEB_CPUS=0.75
WORKER_MEM_LIMIT=640m
WORKER_NODE_HEAP_MB=384
WORKER_CPUS=0.5
CLICKHOUSE_MEM_LIMIT=1g
CLICKHOUSE_CPUS=1.0
LF_POSTGRES_MEM_LIMIT=256m
REDIS_MEM_LIMIT=128m
MINIO_MEM_LIMIT=256m
EOF
fi

echo "✓ wrote $(pwd)/.env (mode $(stat -c %a .env 2>/dev/null || stat -f %Lp .env)):"
grep -oE '^[A-Z_]+' .env | sed 's/^/    /'
